SELECT 
    EMPLOYEES.EMP_ID,
    EMPLOYEES.FULL_NAME,
    EMPLOYEES.GENDER,
    DEPARTMENTS.DEPT_NAME,
    EMPLOYEES.SALARY
FROM EMPLOYEES
JOIN DEPARTMENTS
ON EMPLOYEES.DEPT_ID = DEPARTMENTS.DEPT_ID;

SELECT 
    EMPLOYEES.FULL_NAME,
    DEPARTMENTS.DEPT_NAME,
    EMPLOYEES.SALARY
FROM EMPLOYEES
JOIN DEPARTMENTS
ON EMPLOYEES.DEPT_ID = DEPARTMENTS.DEPT_ID
ORDER BY EMPLOYEES.SALARY DESC;

